import { EvidenceChip } from '@/components/EvidenceChip';
import ui from '@/components/ui.module.css';
import { EVIDENCE_LABELS, MIMICRY_TARGETS, RECONSTRUCTION_LABELS } from '@/data/mimicry';
import { REFERENCES, type Reference } from '@/data/references';
import styles from './SourcesStage.module.css';

const KIND_LABELS: Record<Reference['kind'], string> = {
  'peer-reviewed': 'Peer-reviewed papers',
  book: 'Books',
  museum: 'Museum and institutional pages',
  database: 'Databases',
};

